<p><strong>Effective Date:</strong> June 2026</p>
<h2><strong>1. Purpose of This Policy</strong></h2>
<p>At Dubai Fotographer (“we,” “our,” or “us”), protecting our clients’ photographs, videos, event content, and personal information is a core part of our business. We understand that many of the projects we work on involve important personal, corporate, and commercial moments that deserve to be handled with care and professionalism.</p>
<p>This Security Policy explains the measures we take to protect client media, maintain secure workflows, safeguard digital assets, and reduce the risk of unauthorized access, loss, misuse, or disclosure of information.</p>
<p>While no digital system can guarantee absolute security, we are committed to implementing reasonable technical, administrative, and operational safeguards to help protect client data throughout the lifecycle of every project.</p>
<hr>
<h2><strong>2. Data Protection Principles</strong></h2>
<p>Our approach to security is guided by three fundamental principles:</p>
<h3><strong>Confidentiality</strong></h3>
<p>We take reasonable measures to ensure that client photographs, videos, project files, and personal information are accessible only to authorized individuals who require access for legitimate business purposes.</p>
<h3><strong>Integrity</strong></h3>
<p>We strive to protect files from unauthorized modification, corruption, accidental deletion, or tampering. Maintaining the accuracy and quality of client content is an important part of our workflow.</p>
<h3><strong>Availability</strong></h3>
<p>We implement storage and backup practices designed to help ensure that project files remain available to authorized users when required for editing, delivery, and project management purposes.</p>
<p>These principles help guide our security decisions and operational practices.</p>
<hr>
<h2><strong>3. Media Security</strong></h2>
<p>The protection of client media is one of our highest priorities.</p>
<p>Throughout a project, we may handle a variety of digital assets, including:</p>
<ul>
<li>Raw photographs</li>
<li>Edited photographs</li>
<li>Raw video footage</li>
<li>Edited videos</li>
<li>Drone footage</li>
<li>Event coverage materials</li>
<li>Corporate media assets</li>
<li>Marketing content</li>
<li>Client-provided files</li></ul>
<p>We take reasonable precautions to protect media files from unauthorized access, accidental loss, corruption, and misuse.</p>
<p>Media files are stored within controlled environments and may be organized using secure storage systems designed to support professional production workflows. Where practical, files may be duplicated across backup systems to reduce the risk of data loss caused by hardware failure or technical issues.</p>
<p>Access to project files is restricted based on operational requirements and project responsibilities.</p>
<hr>
<h2><strong>4. File Storage and Transfer</strong></h2>
<p>Dubai Fotographer uses secure methods to store, manage, and deliver digital content.</p>
<h3><strong>Secure Storage</strong></h3>
<p>Project files may be stored on:</p>
<ul>
<li>Professional workstations</li>
<li>Encrypted storage devices</li>
<li>Network storage systems</li>
<li>Reputable cloud storage platforms</li>
<li>Backup storage environments</li></ul>
<p>Storage solutions are selected based on reliability, security, and operational requirements.</p>
<h3><strong>Secure File Transfers</strong></h3>
<p>When delivering content to clients, we may use secure file transfer methods including:</p>
<ul>
<li>Password-protected download links</li>
<li>Private online galleries</li>
<li>Cloud-based file delivery services</li>
<li>Secure transfer platforms</li></ul>
<p>Where available, encrypted connections are used during file transmission to help protect content while it is being transferred over the internet.</p>
<h3><strong>Download Security</strong></h3>
<p>Clients are encouraged to download delivered files promptly and store them securely within their own systems. While we may retain project files for a period of time, long-term archival storage is not guaranteed unless specifically agreed in writing.</p>
<hr>
<h2><strong>5. Access Control</strong></h2>
<p>Access control plays an important role in protecting client content.</p>
<p>We follow the principle of providing access only to individuals who require it to perform their responsibilities.</p>
<p>Access may be granted to:</p>
<ul>
<li>Photographers</li>
<li>Videographers</li>
<li>Editors</li>
<li>Project managers</li>
<li>Administrative personnel</li>
<li>Approved contractors working on a project</li></ul>
<p>Access permissions are limited based on operational needs and project involvement.</p>
<p>Where practical, user accounts, passwords, permissions, and authentication controls are used to help protect systems and project files. Unauthorized access, sharing, copying, or disclosure of client content is prohibited and may result in disciplinary action, termination of contracts, or legal action where appropriate.</p>
<hr>
<h2><strong>6. Editing System Security</strong></h2>
<p>Editing environments often contain valuable client media and project assets. As a result, we take reasonable measures to secure the systems used throughout the production process.</p>
<p>Our security practices may include:</p>
<ul>
<li>Use of licensed software</li>
<li>Software updates and security patches</li>
<li>Device password protection</li>
<li>Antivirus and malware protection tools</li>
<li>Secure user authentication practices</li>
<li>Restricted administrative access</li>
<li>Data backup procedures</li></ul>
<p>We encourage our team members and contractors to follow responsible cybersecurity practices and maintain secure working environments. Although we take precautions to reduce risks, technology-related incidents can still occur despite reasonable safeguards.</p>
<hr>
<h2><strong>7. Client Data Protection</strong></h2>
<p>In addition to media content, we may collect and process certain client information as part of our services.</p>
<p>Examples may include:</p>
<ul>
<li>Names</li>
<li>Email addresses</li>
<li>Phone numbers</li>
<li>Company details</li>
<li>Event information</li>
<li>Venue information</li>
<li>Booking information</li>
<li>Project communications</li></ul>
<p>We use this information only for legitimate business purposes, including project management, communication, service delivery, invoicing, and customer support. We do not sell personal information to third parties.</p>
<p>We do not use client media or personal information in ways that are inconsistent with our Privacy Policy, contractual commitments, or applicable legal obligations. Where clients require confidentiality arrangements, additional restrictions may be agreed upon before project commencement.</p>
<hr>
<h2><strong>8. Third-Party Tools and Services</strong></h2>
<p>To support our operations, we may use trusted third-party service providers.</p>
<p>These providers may include:</p>
<ul>
<li>Cloud storage platforms</li>
<li>File delivery services</li>
<li>Project management systems</li>
<li>Editing software providers</li>
<li>Communication platforms</li>
<li>Backup service providers</li></ul>
<p>We make reasonable efforts to select reputable providers that maintain appropriate security standards. However, third-party services operate independently and maintain their own security practices, policies, and terms of use.</p>
<p>While we seek to work with trusted providers, we cannot guarantee the security performance of systems that are owned, operated, or controlled by third parties. Clients are encouraged to review the privacy and security policies of any third-party platforms involved in project delivery.</p>
<hr>
<h2><strong>9. Risk Disclaimer</strong></h2>
<p>Although we implement security measures designed to protect client content and information, no technology system, network, cloud service, software platform, or digital storage environment can be considered completely secure.</p>
<p>Cybersecurity threats continue to evolve and may include:</p>
<ul>
<li>Malware</li>
<li>Ransomware</li>
<li>Phishing attacks</li>
<li>Unauthorized access attempts</li>
<li>System failures</li>
<li>Human error</li>
<li>Service interruptions</li>
<li>Data corruption</li></ul>
<p>For this reason, we cannot guarantee absolute protection against every possible security incident. Our commitment is to take reasonable and appropriate steps to reduce risks and respond responsibly when issues arise.</p>
<hr>
<h2><strong>10. Incident Handling</strong></h2>
<p>If we become aware of a security incident that may affect client information or project content, we will take reasonable steps to investigate and respond appropriately.</p>
<p>Depending on the nature of the incident, our response may include:</p>
<ul>
<li>Identifying the source of the issue</li>
<li>Securing affected systems</li>
<li>Assessing the impact</li>
<li>Recovering data where possible</li>
<li>Implementing corrective measures</li>
<li>Notifying affected clients when appropriate</li></ul>
<p>Our objective is to address incidents promptly, reduce further risk, and improve future security measures. Not every technical issue will constitute a reportable security incident, but significant events will be handled with transparency and professionalism.</p>
<hr>
<h2><strong>11. Client Responsibilities</strong></h2>
<p>Security is a shared responsibility.</p>
<p>Clients can help protect their content and information by:</p>
<ul>
<li>Keeping download links confidential</li>
<li>Using strong passwords</li>
<li>Storing delivered files securely</li>
<li>Maintaining secure devices and networks</li>
<li>Promptly downloading delivered content</li>
<li>Not sharing private access credentials</li>
<li>Verifying recipient information before forwarding files</li></ul>
<p>If clients suspect unauthorized access to delivered content, they should notify us as soon as possible. We cannot be responsible for security issues that occur after files have been downloaded, transferred, copied, or shared outside of systems under our control.</p>
<hr>
<h2><strong>12. Policy Updates</strong></h2>
<p>We may update this Security Policy from time to time to reflect changes in technology, business operations, legal requirements, industry standards, or security practices. Any updated version will be published on our website together with a revised effective date.</p>
<p>Continued use of our services following publication of an updated policy constitutes acceptance of the revised version.</p>
