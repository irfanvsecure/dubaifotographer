<h2><strong>1. Purpose of This Policy</strong></h2>
<p>At Dubai Fotographer, we believe that excellent customer support is an essential part of delivering professional photography and videography services. Whether you are booking a wedding photographer, planning a corporate shoot, organizing an event, or requesting post-production services, our team is committed to providing clear communication and practical assistance throughout your project.</p>
<p>This Support Policy explains the support services we provide before, during, and after a project. It outlines how clients can contact us, what types of assistance are available, expected response times, and the responsibilities of both Dubai Fotographer and the client.</p>
<p>Our goal is to create a smooth and professional experience from initial enquiry through final delivery of photographs, videos, and other project deliverables.</p>
<hr>
<h2><strong>2. Scope of Support</strong></h2>
<p>We provide support throughout various stages of a project to help clients plan, coordinate, and successfully complete their photography or videography requirements.</p>
<p>Our support services may include:</p>
<h3><strong>Booking Assistance</strong></h3>
<p>We assist clients with service enquiries, package selection, quotation requests, scheduling availability, and project planning discussions.</p>
<h3><strong>Shoot Planning Support</strong></h3>
<p>Our team can provide guidance regarding shoot requirements, timelines, equipment considerations, coverage recommendations, and production planning.</p>
<h3><strong>Location Coordination Guidance</strong></h3>
<p>Where appropriate, we may offer recommendations regarding locations, access considerations, lighting conditions, scheduling factors, and logistical planning. However, responsibility for obtaining permits, venue approvals, and location access remains with the client unless otherwise agreed.</p>
<h3><strong>Editing and Revision Requests</strong></h3>
<p>Clients may contact us regarding editing updates, revision requests, post-production progress, and delivery timelines.</p>
<h3><strong>Delivery Assistance</strong></h3>
<p>We provide support for file delivery, download instructions, access links, gallery navigation, and related delivery questions.</p>
<h3><strong>File Access Support</strong></h3>
<p>If a client experiences difficulty accessing delivered content, our team will make reasonable efforts to assist with restoring access where files remain available within our retention period.</p>
<hr>
<h2><strong>3. Support Channels</strong></h2>
<p>Clients may contact Dubai Fotographer through the following support channels:</p>
<h3><strong>Email Support</strong></h3>
<p>Email is recommended for quotations, project planning, revision requests, file delivery enquiries, and non-urgent support matters.</p>
<h3><strong>Phone Support</strong></h3>
<p>Phone support is available for urgent project discussions, booking enquiries, and time-sensitive matters.</p>
<h3><strong>WhatsApp Support</strong></h3>
<p>WhatsApp is commonly used for booking coordination, shoot-day communication, scheduling updates, and quick support requests.</p>
<h3><strong>On-Location Coordination</strong></h3>
<p>For events, weddings, corporate productions, and commercial projects, designated team members may provide on-site coordination and communication during the scheduled shoot.</p>
<p>The most appropriate communication method may vary depending on the nature and urgency of the request.</p>
